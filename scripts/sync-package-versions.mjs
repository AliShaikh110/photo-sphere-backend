import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

import {
  PUBLISHED_PACKAGES,
  constantPrefix,
  readManifest,
  repositoryRoot
} from './shared-packages.mjs';

/**
 * Regenerates the runtime version constant each shared package exports.
 *
 * A package that cannot state its own version at runtime cannot take part in
 * the compatibility check, and a hand-maintained constant drifts from
 * `package.json` on the first release nobody double-checks. This generates it,
 * `packages:check` fails when the two disagree, and the release command runs
 * both.
 */

export function packageVersionSource(directoryName, packageName, version) {
  const prefix = constantPrefix(directoryName);
  return [
    '// Generated by scripts/sync-package-versions.mjs from package.json.',
    '// Do not edit by hand; run `npm run packages:version -- <version>`.',
    '',
    '/** The npm name this package is published under. */',
    `export const ${prefix}_PACKAGE_NAME = '${packageName}' as const;`,
    '',
    '/** The released version of this package, readable at runtime. */',
    `export const ${prefix}_PACKAGE_VERSION = '${version}' as const;`,
    ''
  ].join('\n');
}

function main() {
  for (const directoryName of PUBLISHED_PACKAGES) {
    const manifest = readManifest(directoryName);
    const target = path.join(repositoryRoot, 'packages', directoryName, 'src', 'package-version.ts');
    const next = packageVersionSource(directoryName, manifest.name, manifest.version);
    let current = null;
    try {
      current = readFileSync(target, 'utf8');
    } catch {
      current = null;
    }
    if (current === next) {
      process.stdout.write(`unchanged ${manifest.name}@${manifest.version}\n`);
      continue;
    }
    writeFileSync(target, next, 'utf8');
    process.stdout.write(`generated ${manifest.name}@${manifest.version}\n`);
  }
}

// Also imported by check-packages.mjs, which compares the generated source
// with what is committed rather than rewriting it.
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';

import * as esbuild from 'esbuild';

import { PUBLISHED_PACKAGES, packageDirectory, repositoryRoot } from './shared-packages.mjs';

/**
 * Builds the publishable JavaScript for the shared package set.
 *
 * `tsc -b` owns the declarations; this owns the runtime output. Each package
 * ships one CommonJS file and one ES module file so the CommonJS API and a
 * bundler-driven frontend can consume the same release, and every specifier
 * that is not relative stays external so a dependency is resolved once by the
 * consumer rather than copied into six tarballs.
 */

/** An absolute path from the machine that produced the artifact. */
const BUILD_MACHINE_PATH = /(^|[^a-zA-Z0-9])([A-Za-z]:[\\/]|\/(home|Users|root)\/)/u;

function declarationFiles(directory) {
  if (!existsSync(directory)) return [];
  return readdirSync(directory).flatMap((entry) => {
    const full = path.join(directory, entry);
    if (statSync(full).isDirectory()) return declarationFiles(full);
    return full.endsWith('.d.ts') ? [full] : [];
  });
}

/**
 * The ES module declaration entry.
 *
 * `./index.js` is resolved by TypeScript back to `index.d.ts`, which keeps one
 * generated declaration tree serving both module systems. Emitting a second
 * tree would mean two sets of types that can disagree.
 */
function writeEsmDeclarationShim(distDirectory) {
  writeFileSync(
    path.join(distDirectory, 'index.d.mts'),
    [
      '// Generated by scripts/build-packages.mjs. Do not edit.',
      '// The ES module view of the declarations emitted alongside it.',
      "export * from './index.js';",
      ''
    ].join('\n'),
    'utf8'
  );
}

async function buildPackage(name) {
  const directory = packageDirectory(name);
  const distDirectory = path.join(directory, 'dist');
  const entry = path.join(directory, 'src', 'index.ts');

  if (!existsSync(entry)) throw new Error(`${name}: missing src/index.ts`);

  const declarationEntry = path.join(distDirectory, 'index.d.ts');
  if (!existsSync(declarationEntry)) {
    throw new Error(
      `${name}: dist/index.d.ts is missing. Run \`npm run build:types\` before building bundles.`
    );
  }

  const shared = {
    entryPoints: [entry],
    bundle: true,
    // Everything that is not a relative import is resolved by the consumer:
    // sibling packages stay separate artifacts and third-party code is never
    // vendored into a tarball we would then have to patch ourselves.
    packages: 'external',
    platform: 'neutral',
    target: 'es2022',
    sourcemap: false,
    legalComments: 'inline',
    logLevel: 'warning'
  };

  await esbuild.build({ ...shared, format: 'cjs', outfile: path.join(distDirectory, 'index.cjs') });
  await esbuild.build({ ...shared, format: 'esm', outfile: path.join(distDirectory, 'index.mjs') });

  writeEsmDeclarationShim(distDirectory);

  const artifacts = ['index.cjs', 'index.mjs', 'index.d.ts', 'index.d.mts'];
  for (const artifact of artifacts) {
    const full = path.join(distDirectory, artifact);
    if (!existsSync(full)) throw new Error(`${name}: build did not produce ${artifact}`);
  }

  // A published artifact must not carry a path from the machine that built it,
  // and must not point a debugger at sources the tarball does not ship.
  const emitted = [
    ...artifacts.map((artifact) => path.join(distDirectory, artifact)),
    ...declarationFiles(distDirectory)
  ];
  for (const file of new Set(emitted)) {
    const contents = readFileSync(file, 'utf8');
    if (contents.includes('sourceMappingURL')) {
      throw new Error(`${path.relative(repositoryRoot, file)} references a source map.`);
    }
    if (BUILD_MACHINE_PATH.test(contents)) {
      throw new Error(
        `${path.relative(repositoryRoot, file)} leaks an absolute path from the build machine.`
      );
    }
  }

  const bytes = artifacts.map((artifact) => {
    const size = statSync(path.join(distDirectory, artifact)).size;
    return `${artifact} ${(size / 1024).toFixed(1)}kB`;
  });
  process.stdout.write(`built @alishaikh110/${name}  ${bytes.join('  ')}\n`);
}

async function main() {
  for (const name of PUBLISHED_PACKAGES) {
    await buildPackage(name);
  }
}

await main();
